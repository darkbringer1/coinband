"""Build the GitHub Pages site in `docs/`: the article and a static, in-browser demo.

- `docs/index.html`: `docs/paper.md` rendered as the article.
- `docs/demo/`: the coinband player (copied from `coinband/static/`) in static mode, replaying precomputed
  backtests from `docs/demo/data/*.json`. No server and no model in the browser.
- `docs/.nojekyll`: serve the files as they are.

Only Binance crypto data goes into the site. Yahoo's terms restrict redistributing its data, so stocks stay in
the run-it-yourself app.

    uv run python experiments/build_site.py --device mps     # forecasts + pages (a few minutes on a GPU)
    uv run python experiments/build_site.py --pages-only     # re-render pages, keep the data

Then publish `docs/` with GitHub Pages (Settings > Pages > Deploy from a branch > main, /docs).
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
DEMO = DOCS / "demo"
DATA = DEMO / "data"
STATIC = ROOT / "coinband" / "static"
REPO_URL = "https://github.com/darkbringer1/coinband"

PAIRS = ["BTCUSDT", "ETHUSDT", "SOLUSDT", "BNBUSDT", "XRPUSDT", "DOGEUSDT", "ADAUSDT", "LINKUSDT"]
MODEL = "mistralai/Timestral-209M"
CONTEXT = 4096
HORIZON = 24
DAYS = 30
PAD_BARS = 2 * HORIZON + 240  # history shown before the first forecast
SUMMARY_KEYS = ("crps_skill", "skill", "coverage", "calibration_error", "direction_hit_rate", "scored")


def build_data(device: str) -> None:
    from coinband import binance_data, cache
    from coinband.backtest import BacktestParams, run_backtest
    from coinband.device import load_forecaster
    from coinband.sessions import future_times

    DATA.mkdir(parents=True, exist_ok=True)
    forecaster = load_forecaster(MODEL, device)
    origins = DAYS * 24
    generated = dt.datetime.now(dt.UTC).strftime("%Y-%m-%d")
    runs = []
    for symbol in PAIRS:
        k = cache.get_klines("binance", symbol, "1h", CONTEXT + origins + PAD_BARS, binance_data.fetch_klines, 3_600_000)
        params = BacktestParams(context=CONTEXT, horizon=HORIZON, stride=1, max_origins=origins)
        bt = run_backtest(forecaster, k.close, params, volume=k.volume)
        bt.pop("raw", None)
        offset = max(0, bt["origins"][0]["index"] - PAD_BARS)
        for o in bt["origins"]:
            o["index"] -= offset
        result = {
            "source": "binance",
            "symbol": k.symbol,
            "info": k.info,
            "interval": "1h",
            "interval_ms": 3_600_000,
            "future_time": future_times(k.open_time, 3_600_000, HORIZON, "UTC", True),
            "model": MODEL,
            "params": {"context": CONTEXT, "horizon": HORIZON, "stride": 1, "max_origins": origins,
                       "trend_window": 0, "covariates": False},
            "time": k.open_time[offset:],
            "close": k.close[offset:],
            "generated": generated,
            **bt,
        }
        for o in result["origins"]:  # 6 significant digits are plenty for drawing and keep the files small
            o["bands"] = [[float(f"{v:.6g}") for v in step] for step in o["bands"]]
        (DATA / f"{symbol}.json").write_text(json.dumps(result, separators=(",", ":"), allow_nan=False))
        live = bt["origins"][-1]["bands"][-1]
        runs.append(
            {
                "symbol": symbol,
                "file": f"data/{symbol}.json",
                "summary": {key: bt["summary"].get(key) for key in SUMMARY_KEYS},
                "live_change": live[2] / k.close[-1] - 1,
            }
        )
        print(f"{symbol}: CRPS skill {bt['summary']['crps_skill'] * 100:+.2f}%", flush=True)
    runs.sort(key=lambda r: -(r["summary"]["crps_skill"] or 0))
    index = {"generated": generated, "model": MODEL, "model_name": MODEL.split("/")[-1], "horizon": HORIZON,
             "days": DAYS, "runs": runs}
    (DATA / "index.json").write_text(json.dumps(index, indent=1))


def build_pages() -> None:
    from coinband.paper import render

    DEMO.mkdir(parents=True, exist_ok=True)
    shutil.copy(STATIC / "app.js", DEMO / "app.js")
    shutil.copy(STATIC / "style.css", DEMO / "style.css")
    page = (STATIC / "index.html").read_text()
    config = json.dumps({"index": "data/index.json", "article": "../", "repo": REPO_URL})
    page = (
        page.replace('href="/style.css"', 'href="style.css"')
        .replace('<script src="/app.js"></script>', f"<script>window.COINBAND_STATIC = {config};</script>\n  <script src=\"app.js\"></script>")
        .replace('href="/paper"', 'href="../"')
        .replace("<title>coinband</title>", "<title>coinband demo: Timestral forecasts on crypto, replayed</title>")
    )
    (DEMO / "index.html").write_text("<!-- generated by experiments/build_site.py from coinband/static -->\n" + page)

    from coinband.paper import rewrite_links

    pages = {
        # name: (markdown, output, prefix to the site root, description)
        "paper": ("paper.md", DOCS / "index.html", "",
                  "We backtested Mistral's Timestral forecaster on eight crypto coins: honest ranges, a small but "
                  "consistent edge over a random walk, and no sense of direction."),
        "risk": ("risk.md", DOCS / "risk" / "index.html", "../",
                 "Timestral against GARCH, EWMA and historical simulation as a crypto risk model: better ranges, "
                 "trustworthy Value-at-Risk, and no proven trading edge yet."),
    }
    for name, (src, out, root, description) in pages.items():
        md = (DOCS / src).read_text()
        md = rewrite_links(md, {"paper": root or "./", "risk": f"{root}risk/"}, figures=f"{root}figures/", demo=f"{root}demo/")
        title = next(line[2:] for line in md.splitlines() if line.startswith("# "))
        nav = (f'<a href="{root or "./"}">Part 1</a><a href="{root}risk/">Part 2</a>'
               f'<a href="{root}demo/">Interactive demo</a><a href="{REPO_URL}">Code on GitHub</a>')
        html = render(md, title=title, nav=nav)
        html = html.replace("<title>", f'<meta name="description" content="{description}"><title>', 1)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(f"<!-- generated by experiments/build_site.py from docs/{src} -->\n" + html)
    (DOCS / ".nojekyll").write_text("")
    print(f"wrote {DOCS / 'index.html'}, {DOCS / 'risk' / 'index.html'} and {DEMO / 'index.html'}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--device", default="mps")
    ap.add_argument("--pages-only", action="store_true")
    args = ap.parse_args()
    if not args.pages_only:
        build_data(args.device)
    build_pages()


if __name__ == "__main__":
    main()
